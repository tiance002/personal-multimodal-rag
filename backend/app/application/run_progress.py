"""Versioned, non-factual progress over the existing committed Run event store."""
from __future__ import annotations

STAGES = frozenset({'run', 'understand', 'retrieval', 'evidence', 'generation', 'validation'})
STATUSES = frozenset({'started', 'completed', 'failed', 'truncated'})
REASONS = frozenset({'NO_CANDIDATES', 'CANCELLED', 'MODEL_OUTPUT_TRUNCATED',
    'MODEL_UNAVAILABLE', 'MODEL_REQUEST_NOT_SENT', 'UNSUPPORTED_ANSWER',
    'INSUFFICIENT_EVIDENCE', 'SECTION_TRUNCATED', 'OUTPUT_CAPACITY_UNVERIFIED',
    'OUTPUT_CAPACITY_UNSUPPORTED', 'CLOUD_EGRESS_DISABLED', 'RUN_LEASE_LOST',
    'MONTHLY_BUDGET_EXCEEDED', 'MODEL_NOT_READY', 'STAGE_FAILED'})


class RunProgress:
    """Best-effort process data; never changes a Run's success or billing facts."""
    def __init__(self, store, run_id):
        self.store, self.run_id = store, run_id

    def emit(self, stage, status, **fields):
        if stage not in STAGES or status not in STATUSES:
            return
        data = dict(schema_version='run-progress/v1', stage=stage, status=status)
        for name in ('candidate_count', 'selected_evidence_count', 'duration_ms'):
            value = fields.get(name)
            if type(value) is int and value >= 0:
                data[name] = value
        role = fields.get('role')
        if role in {'cheap', 'expensive'}:
            data['role'] = role
        attempt = fields.get('attempt_id')
        if isinstance(attempt, str) and 0 < len(attempt) <= 128:
            # Attempt identifiers are generated by the service, not prompts.
            import re
            if re.fullmatch(r'[A-Za-z0-9_.:-]+', attempt):
                data['attempt_id'] = attempt
        reason = fields.get('reason_code')
        if reason is not None:
            data['reason_code'] = reason if reason in REASONS else 'STAGE_FAILED'
        try:
            self.store.append_event(self.run_id, 'run.progress', data)
        except Exception:
            # The authoritative pipeline and final transaction remain untouched.
            pass
